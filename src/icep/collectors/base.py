"""The collector contract: turn a sample Linux input into a structured evidence result.

Each collector is a pure function ``run(samples_dir, today) -> CollectorResult``: it reads a
committed sample (an sshd_config, an auditd rules file, a scanner report, ...), evaluates it against
a baseline, and returns findings. :func:`render_markdown` turns any result into a consistent,
deterministic Markdown report -- the artifact that becomes a piece of evidence. Nothing here reads
the wall clock; the report date is the injected ``today``, so re-running the seed is byte-stable.
"""

from __future__ import annotations

from datetime import date
from enum import StrEnum
from typing import Protocol

from pydantic import BaseModel, ConfigDict, Field

__all__ = [
    "CheckStatus",
    "Finding",
    "CollectorResult",
    "Collector",
    "render_markdown",
]


class CheckStatus(StrEnum):
    """Outcome of a single check."""

    PASS = "pass"
    WARN = "warn"
    FAIL = "fail"


class Finding(BaseModel):
    """One evaluated check within a collector run."""

    model_config = ConfigDict(extra="forbid")

    id: str = Field(min_length=1, max_length=60)
    description: str = Field(min_length=1, max_length=200)
    status: CheckStatus
    severity: str = Field(
        default="medium", description="high|medium|low; meaningful for warn/fail."
    )
    observed: str = Field(default="", max_length=300)
    recommendation: str = Field(default="", max_length=300)


class CollectorResult(BaseModel):
    """The structured output of a collector run (rendered to Markdown for the evidence artifact)."""

    model_config = ConfigDict(extra="forbid")

    collector: str = Field(min_length=1, max_length=60)
    title: str = Field(min_length=1, max_length=200)
    target: str = Field(min_length=1, max_length=200, description="What was evaluated.")
    report_date: date
    summary: str = Field(min_length=1, max_length=400)
    control_refs: list[str] = Field(default_factory=list)
    nis2_areas: list[str] = Field(default_factory=list)
    findings: list[Finding] = Field(default_factory=list)

    @property
    def passed(self) -> int:
        return sum(1 for f in self.findings if f.status is CheckStatus.PASS)

    @property
    def warned(self) -> int:
        return sum(1 for f in self.findings if f.status is CheckStatus.WARN)

    @property
    def failed(self) -> int:
        return sum(1 for f in self.findings if f.status is CheckStatus.FAIL)

    @property
    def total(self) -> int:
        return len(self.findings)

    @property
    def coverage_pct(self) -> float:
        """Percentage of checks that passed (0-100, one decimal)."""
        return round(100.0 * self.passed / self.total, 1) if self.total else 0.0


class Collector(Protocol):
    """A callable that evaluates committed samples into a :class:`CollectorResult`."""

    name: str

    def run(self, samples_dir: object, today: date) -> CollectorResult: ...


_STATUS_MARK = {CheckStatus.PASS: "PASS", CheckStatus.WARN: "WARN", CheckStatus.FAIL: "FAIL"}


def render_markdown(result: CollectorResult) -> str:
    """Render a collector result as a deterministic Markdown evidence artifact."""
    lines: list[str] = []
    lines.append(f"# {result.title}")
    lines.append("")
    lines.append(f"- **Collector:** `{result.collector}`")
    lines.append(f"- **Target:** {result.target}")
    lines.append(f"- **Report date:** {result.report_date.isoformat()}")
    if result.control_refs:
        lines.append(f"- **Controls:** {', '.join(result.control_refs)}")
    if result.nis2_areas:
        lines.append(f"- **NIS2:** {', '.join(result.nis2_areas)}")
    lines.append(
        f"- **Result:** {result.passed} passed, {result.warned} warning(s), "
        f"{result.failed} failed of {result.total} checks ({result.coverage_pct}% pass)"
    )
    lines.append("")
    lines.append(f"> {result.summary}")
    lines.append("")
    lines.append("| Check | Result | Severity | Observed | Recommendation |")
    lines.append("| --- | --- | --- | --- | --- |")
    for finding in result.findings:
        mark = _STATUS_MARK[finding.status]
        severity = finding.severity if finding.status is not CheckStatus.PASS else "-"
        observed = finding.observed or "-"
        recommendation = finding.recommendation or "-"
        lines.append(
            f"| {finding.description} | {mark} | {severity} | {observed} | {recommendation} |"
        )
    lines.append("")
    lines.append(
        "_Generated by the `icep` evidence collector from a committed sample. "
        "This artifact is illustrative demo data for the PaketPort Systems ISMS portfolio._"
    )
    lines.append("")
    return "\n".join(lines)
