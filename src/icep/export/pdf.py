"""Render the audit pack to a single PDF with WeasyPrint.

WeasyPrint (and the ``markdown`` renderer) live behind the optional ``pdf`` extra, so the core test
gate stays dependency-free. The same Markdown sections that form the bundle are converted to HTML
and laid out with a small print stylesheet, so the PDF and the Markdown never drift. Set
``SOURCE_DATE_EPOCH`` for a byte-stable ``/CreationDate``.
"""

from __future__ import annotations

from datetime import date
from pathlib import Path

__all__ = ["PDF_AVAILABLE", "build_pdf", "markdown_to_pdf"]

try:  # pragma: no cover - import guard exercised by environments without the pdf extra
    import markdown as _markdown
    import weasyprint as _weasyprint

    PDF_AVAILABLE = True
except ImportError:  # pragma: no cover
    PDF_AVAILABLE = False


_PRINT_CSS = """
@page {
  size: A4;
  margin: 20mm 16mm 18mm 16mm;
  @bottom-right { content: counter(page) " / " counter(pages); font-size: 9pt; color: #64748b; }
  @bottom-left { content: "PaketPort Systems — ISMS audit pack"; font-size: 9pt; color: #64748b; }
}
* { box-sizing: border-box; }
body { font-family: "DejaVu Sans", "Noto Sans", sans-serif; font-size: 10pt; color: #1e293b; line-height: 1.45; }
h1 { font-size: 17pt; color: #1e1b4b; border-bottom: 2px solid #4f46e5; padding-bottom: 4px; }
h2 { font-size: 13pt; color: #3730a3; margin-top: 16px; }
h3 { font-size: 11pt; color: #3730a3; }
section { page-break-before: always; }
table { border-collapse: collapse; width: 100%; font-size: 8.2pt; margin: 8px 0; }
th, td { border: 1px solid #cbd5e1; padding: 3px 5px; text-align: left; vertical-align: top; }
th { background: #eef2ff; color: #1e1b4b; }
tr:nth-child(even) td { background: #f8fafc; }
blockquote { color: #475569; border-left: 3px solid #c7d2fe; margin: 8px 0; padding: 2px 10px; }
code { font-family: "DejaVu Sans Mono", monospace; font-size: 8pt; }
.cover { page-break-after: always; page-break-before: avoid; text-align: center; padding-top: 60mm; }
.cover .brand { color: #4f46e5; font-weight: bold; letter-spacing: 2px; }
.cover h1 { font-size: 30pt; border: none; color: #1e1b4b; margin: 8px 0; }
.cover .meta { color: #475569; font-size: 11pt; margin-top: 20mm; }
"""


def _cover(org_name: str, today: date) -> str:
    return (
        '<div class="cover">'
        '<div class="brand">INFORMATION SECURITY MANAGEMENT SYSTEM</div>'
        "<h1>Audit Pack</h1>"
        f"<div>{org_name}</div>"
        '<div class="meta">'
        "ISO/IEC 27001:2022 &middot; NIS2 readiness<br/>"
        f"Report date: {today.isoformat()}<br/>"
        "Generated by <code>icep</code> (offline, deterministic)"
        "</div></div>"
    )


def build_pdf(
    org_name: str,
    sections: dict[str, str],
    section_order: list[tuple[str, str]],
    today: date,
    out_path: Path,
) -> None:
    """Render ``sections`` (slug -> Markdown) to a single PDF at ``out_path``."""
    if not PDF_AVAILABLE:  # pragma: no cover - guarded by callers
        raise RuntimeError("PDF export needs the 'pdf' extra: uv sync --extra pdf")

    parts = [_cover(org_name, today)]
    for slug, _title in section_order:
        html = _markdown.markdown(sections[slug], extensions=["tables", "sane_lists"])
        parts.append(f"<section>{html}</section>")

    document = (
        '<!DOCTYPE html><html><head><meta charset="utf-8">'
        f"<style>{_PRINT_CSS}</style></head><body>{''.join(parts)}</body></html>"
    )
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    _weasyprint.HTML(string=document).write_pdf(str(out_path))


def markdown_to_pdf(markdown_text: str, out_path: Path, base_url: str | None = None) -> None:
    """Render a single Markdown document (e.g. the README) to a PDF at ``out_path``.

    ``base_url`` lets relative image paths (diagrams, screenshots) resolve from the repo root.
    """
    if not PDF_AVAILABLE:  # pragma: no cover - guarded by callers
        raise RuntimeError("PDF export needs the 'pdf' extra: uv sync --extra pdf")
    html = _markdown.markdown(markdown_text, extensions=["tables", "sane_lists", "fenced_code"])
    document = (
        '<!DOCTYPE html><html><head><meta charset="utf-8">'
        f"<style>{_PRINT_CSS}</style></head><body>"
        f'<section style="page-break-before: avoid">{html}</section></body></html>'
    )
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    _weasyprint.HTML(string=document, base_url=base_url).write_pdf(str(out_path))
